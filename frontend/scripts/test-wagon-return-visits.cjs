const assert = require('node:assert/strict');
const esbuild = require('esbuild');
const vm = require('node:vm');
const path = require('node:path');
const out = esbuild.buildSync({entryPoints:[path.join(__dirname,'../src/shared/utils/wagonQueueState.ts')],bundle:true,platform:'node',format:'cjs',write:false});
const mod={exports:{}};vm.runInNewContext(out.outputFiles[0].text,{module:mod,exports:mod.exports,require});
const {unregisteredArrivals,registeredVisitKeys,wagonVisitKey}=mod.exports;
const old={id:'old-entry',wagons:[{wagonNumber:'58212473'}]};
const newer={id:'new-entry',wagons:[{wagonNumber:'58212473'}]};
const regs=[{emptyWagonArrivalId:old.id,exitedToKengsoyAt:'2026-09-04',wagonRoutes:[{wagonNumber:'58212473',sourceArrivalId:old.id}]}];
let result=unregisteredArrivals([old,newer],regs);
assert.equal(result[0].wagons.length,0);
assert.equal(result[1].wagons.length,1,'new entry must survive old departure');
const mixed=[{emptyWagonArrivalId:'other',wagonRoutes:[{wagonNumber:'58212473',sourceArrivalId:newer.id}]}];
assert(!registeredVisitKeys(mixed,[old,newer]).has(wagonVisitKey(old.id,'58212473')));
assert(registeredVisitKeys(mixed,[old,newer]).has(wagonVisitKey(newer.id,'58212473')));
result=unregisteredArrivals([old,newer],[{emptyWagonArrivalId:old.id,wagonRoutes:[]}]);
assert.equal(result[1].wagons.length,1,'legacy registry stays scoped to its entry');
console.log('PASS: repeat entry, mixed source routes, legacy registry all remain visit-scoped.');
