import assert from 'node:assert/strict';
import { build } from 'esbuild';
const { outputFiles } = await build({ entryPoints: ['src/shared/utils/wagonFlowTiles.ts'], bundle: true, platform: 'node', format: 'esm', write: false });
const { buildWagonFlowMetrics: metrics } = await import(`data:text/javascript;base64,${Buffer.from(outputFiles[0].text).toString('base64')}`);
const time = '2026-09-11T06:00:00Z';
const arrival = { id: 'a', createdAt: time, arrivalDate: time, stage: 'SecurityInspection', wagons: [] };
assert.deepEqual(metrics([{ ...arrival, entryPermitPermitApprovedAt: time }], []).ownerSequenceDone.w4, [true, false]);
const unit = { status: 'SealPending', grossWeight: 70, grossWeighedAt: time, sealNumber: '123', sealConfirmedByScaleAt: time };
let result = metrics([{ ...arrival, stage: 'SealInstallation', wagons: [unit] }], []);
assert.equal(result.splitApprovedAt.sealScale, time);
assert.equal(result.splitApprovedAt.sealSecurity, null);
result = metrics([{ ...arrival, stage: 'SealInstallation', wagons: [{ ...unit, sealConfirmedBySecurityAt: time }] }], []);
assert.equal(result.splitApprovedAt.sealSecurity, time);
const registry = { id: 'r', emptyWagonArrivalId: 'a', preparedAt: time };
result = metrics([arrival], [registry]);
assert.equal(result.splitApprovedAt.registryCreate, time);
assert.equal(result.approvedAt.w9, null);
result = metrics([arrival], [{ ...registry, isApprovedByPermit: true, isApprovedBySecurity: true, securityApprovedAt: time }]);
assert.equal(result.splitApprovedAt.exitSecurity, time);
assert.equal(result.approvedAt.w11, null);
const exited = { ...registry, exitedToKengsoyAt: time, isSentToOneC: true, sentToOneCAt: time };
assert.equal(metrics([{ ...arrival, stage: 'Exited' }], [exited]).approvedAt.w12, null);
assert.equal(metrics([{ ...arrival, stage: 'Exited' }], [{ ...exited, isSentToENakl: true, sentToENaklAt: time }]).approvedAt.w12, time);
console.log('Wagon flow: all 7 regression scenarios passed.');
